export function resolveStrings(localeCode = 'de') {
  const short = String(localeCode || 'de').toLowerCase().slice(0, 2);
  return STRINGS[short] || STRINGS.en;
}

export function detectInitialLocale(savedLocale) {
  if (savedLocale && STRINGS[savedLocale]) return savedLocale;
  const nav = globalThis.navigator?.language?.slice(0, 2)?.toLowerCase();
  if (nav && STRINGS[nav]) return nav;
  return 'de';
}
